import streamlit as st
import pandas as pd
import plotly.express as px
from datetime import datetime

st.set_page_config(
    page_title="Reports",
    page_icon="📄",
    layout="wide"
)

# -----------------------------
# Load Dataset
# -----------------------------

@st.cache_data
def load_data():
    df = pd.read_csv("data/raw/dailyActivity_merged.csv")
    df["ActivityDate"] = pd.to_datetime(df["ActivityDate"])
    return df

df = load_data()

# -----------------------------
# Header
# -----------------------------

st.title("📄 FitIntel AI Reports")

st.write(
    "Generate AI-powered fitness reports and export insights."
)

st.divider()

# -----------------------------
# KPIs
# -----------------------------

c1, c2, c3, c4 = st.columns(4)

c1.metric(
    "Average Steps",
    f"{int(df.TotalSteps.mean()):,}"
)

c2.metric(
    "Average Calories",
    f"{int(df.Calories.mean())}"
)

c3.metric(
    "Average Distance",
    f"{df.TotalDistance.mean():.2f} km"
)

goal_rate = (
    (df.TotalSteps >= 10000).sum() /
    len(df)
) * 100

c4.metric(
    "Goal Achievement",
    f"{goal_rate:.1f}%"
)

st.divider()
# ---------------------------------------------------
# EXECUTIVE SUMMARY
# ---------------------------------------------------

st.subheader("📊 Executive Summary")

left, right = st.columns([2, 1])

with left:

    fig = px.line(
        df,
        x="ActivityDate",
        y="TotalSteps",
        title="Daily Steps Trend",
        markers=True,
        template="plotly_white"
    )

    fig.update_layout(height=350)

    st.plotly_chart(
        fig,
        use_container_width=True
    )

with right:

    st.markdown("### 📈 AI Insights")

    avg_steps = int(df["TotalSteps"].mean())
    avg_calories = int(df["Calories"].mean())
    avg_distance = df["TotalDistance"].mean()
    avg_sedentary = int(df["SedentaryMinutes"].mean())

    st.info(f"🚶 Average Daily Steps : **{avg_steps:,}**")
    st.info(f"🔥 Average Calories : **{avg_calories} kcal**")
    st.info(f"📏 Average Distance : **{avg_distance:.2f} km**")
    st.info(f"🪑 Sedentary Time : **{avg_sedentary} min/day**")

st.divider()

# ---------------------------------------------------
# AI GENERATED REPORT
# ---------------------------------------------------

st.subheader("🤖 AI Generated Report")

if avg_steps >= 10000:

    activity = "Excellent"

elif avg_steps >= 7500:

    activity = "Good"

else:

    activity = "Needs Improvement"

if avg_sedentary > 800:

    sedentary_status = "High"

else:

    sedentary_status = "Healthy"

report = f"""
FITINTEL AI FITNESS REPORT

Report Generated:
{datetime.now().strftime("%d-%m-%Y %H:%M")}

----------------------------------------------------

Average Steps : {avg_steps:,}

Average Calories : {avg_calories}

Average Distance : {avg_distance:.2f} km

Goal Achievement Rate : {goal_rate:.2f}%

Sedentary Time : {avg_sedentary} minutes

----------------------------------------------------

Overall Activity Level : {activity}

Sedentary Status : {sedentary_status}

----------------------------------------------------

AI Recommendations

• Walk at least 10,000 steps daily

• Reduce sedentary time

• Stay hydrated

• Exercise regularly

• Sleep 7-8 hours daily

----------------------------------------------------

Generated by FitIntel AI
"""

st.text_area(
    "Generated Report",
    report,
    height=350
)

st.divider()
# ---------------------------------------------------
# DOWNLOAD REPORTS
# ---------------------------------------------------

st.subheader("📥 Export Reports")

col1, col2 = st.columns(2)

with col1:

    st.download_button(
        label="📄 Download AI Report (.txt)",
        data=report,
        file_name="FitIntel_AI_Report.txt",
        mime="text/plain",
        use_container_width=True
    )

with col2:

    csv = df.to_csv(index=False).encode("utf-8")

    st.download_button(
        label="📊 Download Dataset (.csv)",
        data=csv,
        file_name="FitIntel_Dataset.csv",
        mime="text/csv",
        use_container_width=True
    )

st.divider()

# ---------------------------------------------------
# VISUAL ANALYTICS
# ---------------------------------------------------

st.subheader("📈 Visual Analytics")

left, right = st.columns(2)

# ---------------- Scatter ----------------

with left:

    fig = px.scatter(
        df,
        x="TotalSteps",
        y="Calories",
        color="Calories",
        title="🔥 Steps vs Calories",
        template="plotly_white"
    )

    fig.update_layout(height=420)

    st.plotly_chart(
        fig,
        use_container_width=True
    )

# ---------------- Pie ----------------

with right:

    activity = pd.cut(
        df["TotalSteps"],
        bins=[0,5000,7500,10000,50000],
        labels=[
            "Low",
            "Moderate",
            "Active",
            "Highly Active"
        ]
    )

    pie = (
        activity
        .value_counts()
        .reset_index()
    )

    pie.columns = [
        "Activity",
        "Count"
    ]

    fig = px.pie(
        pie,
        names="Activity",
        values="Count",
        hole=0.45,
        title="🥧 Activity Distribution",
        template="plotly_white"
    )

    fig.update_layout(height=420)

    st.plotly_chart(
        fig,
        use_container_width=True
    )

st.divider()

# ---------------------------------------------------
# CORRELATION MATRIX
# ---------------------------------------------------

st.subheader("🔥 Correlation Matrix")

corr = df.select_dtypes(include="number").corr()

fig = px.imshow(
    corr,
    text_auto=".2f",
    color_continuous_scale="Viridis",
    aspect="auto",
    title="Feature Correlation"
)

fig.update_layout(height=650)

st.plotly_chart(
    fig,
    use_container_width=True
)

st.divider()

# ---------------------------------------------------
